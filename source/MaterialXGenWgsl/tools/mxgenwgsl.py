# Sampler identifiers that appear in genglsl lib sources after $-token expansion.
# Each gets texture operation rewrites applied via TEXTURE_REWRITE_RULES below.
TEXTURE_SAMPLER_NAMES = [
    "MTLXTOK_texSamplerSampler2D", "mtlx_tex_sampler",
    "mtlx_env_radiance_stub", "mtlx_env_irradiance_stub", "mtlx_albedo_table",
    "MTLXTOK_envRadianceSampler2D",
]

# GLSL texture → placeholder rewrite rules. Applied for each sampler name above.
# {S} is replaced with the escaped sampler name at apply time.
# Rules are applied in order — swizzle-specific patterns must come before the no-swizzle fallback.
TEXTURE_REWRITE_RULES = [
    # textureLod rules — use distinct _level_ placeholders so the LOD argument survives
    # the naga round-trip and is restored as textureSampleLevel on the WGSL side.
    # textureLod(sampler, uv, lod).rgb → mtlx_tex_lookup_level_rgb(uv, lod)
    (r"textureLod\s*\(\s*{S}\s*,\s*([^,)]+),\s*([^,)]+)\)\.rgb",
     r"mtlx_tex_lookup_level_rgb(\1, \2)"),
    # textureLod(sampler, uv, lod) [no swizzle] → mtlx_tex_lookup_level_rgba(uv, lod)
    (r"textureLod\s*\(\s*{S}\s*,\s*([^,)]+),\s*([^,)]+)\)",
     r"mtlx_tex_lookup_level_rgba(\1, \2)"),
    # textureGrad rules — use distinct _grad_ placeholders so both derivative arguments
    # survive the naga round-trip and are restored as textureSampleGrad on the WGSL side.
    # textureGrad(sampler, uv, dx, dy).rgb → mtlx_tex_lookup_grad_rgb(uv, dx, dy)
    (r"textureGrad\s*\(\s*{S}\s*,\s*([^,)]+),\s*([^,)]+),\s*([^,)]+)\)\.rgb",
     r"mtlx_tex_lookup_grad_rgb(\1, \2, \3)"),
    # textureGrad(sampler, uv, dx, dy) [no swizzle] → mtlx_tex_lookup_grad_rgba(uv, dx, dy)
    (r"textureGrad\s*\(\s*{S}\s*,\s*([^,)]+),\s*([^,)]+),\s*([^,)]+)\)",
     r"mtlx_tex_lookup_grad_rgba(\1, \2, \3)"),
    # texture rules — implicit-derivative sampling (textureSample on restore).
    # texture(sampler, uv).rgb → mtlx_tex_lookup_rgb(uv, 0.0)
    (r"texture\s*\(\s*{S}\s*,\s*([^,)]+)\)\.rgb",
     r"mtlx_tex_lookup_rgb(\1, 0.0)"),
    # texture(sampler, uv).xy or .rg → mtlx_tex_lookup_rg(uv)
    (r"texture\s*\(\s*{S}\s*,\s*([^,)]+)\)\.(?:rg|xy)",
     r"mtlx_tex_lookup_rg(\1)"),
    # texture(sampler, uv).b → mtlx_tex_lookup_b(uv)
    (r"texture\s*\(\s*{S}\s*,\s*([^,)]+)\)\.b",
     r"mtlx_tex_lookup_b(\1)"),
    # texture(sampler, uv).r → mtlx_tex_lookup_r(uv)
    (r"texture\s*\(\s*{S}\s*,\s*([^,)]+)\)\.r",
     r"mtlx_tex_lookup_r(\1)"),
    # texture(sampler, uv) with no swizzle → mtlx_tex_lookup_rgba(uv)
    (r"texture\s*\(\s*{S}\s*,\s*([^,)]+)\)(?!\.)",
     r"mtlx_tex_lookup_rgba(\1)"),
    # textureSize(sampler, 0).x → mtlx_tex_size_x()
    (r"textureSize\s*\(\s*{S}\s*,\s*0\s*\)\.x",
     r"mtlx_tex_size_x()"),
    # textureSize(sampler, 0) → vec2(256.0)
    (r"textureSize\s*\(\s*{S}\s*,\s*0\s*\)",
     r"vec2(256.0)"),
]


def expandLibTokens(text, libroot=None):
    '''Replace MaterialX $-tokens with MTLXTOK sentinels and rewrite GLSL texture ops to
    naga-parseable placeholder functions. After transpile, applyWgslLibPostRestore converts
    these placeholders back to proper WGSL textureSample() calls.'''
    if libroot is None:
        libroot = _activeLibroot()
    text, tokenMap = replaceTokenSentinels(text)
    # Replace sampler2D declarations with int stubs (naga doesn't need real samplers).
    text = re.sub(r"\bsampler2D\s+mtlx_\w+\b", "int mtlx_sampler_stub", text)
    # Apply texture rewrite rules for each known sampler name.
    for sampler in TEXTURE_SAMPLER_NAMES:
        escaped = re.escape(sampler)
        for pattern, replacement in TEXTURE_REWRITE_RULES:
            text = re.sub(pattern.replace("{S}", escaped), replacement, text)
    return text, tokenMap


# Texture-lookup helper → WGSL texture call rewrite rules.
# Each entry: (regex matching the naga placeholder call, replacement with $texSamplerSampler2D).
# Level and grad rules must come before the plain rules to avoid partial matches.
_TEX_LOOKUP_RULES = [
    # textureSampleLevel restores (from textureLod placeholders)
    (re.compile(r"mtlx_tex_lookup_level_rgb\(([^,)]+),\s*([^)]+)\)"),  r"textureSampleLevel($texSamplerSampler2D, \1, \2).rgb"),
    (re.compile(r"mtlx_tex_lookup_level_rgba\(([^,)]+),\s*([^)]+)\)"), r"textureSampleLevel($texSamplerSampler2D, \1, \2)"),
    # textureSampleGrad restores (from textureGrad placeholders)
    (re.compile(r"mtlx_tex_lookup_grad_rgb\(([^,)]+),\s*([^,)]+),\s*([^)]+)\)"),  r"textureSampleGrad($texSamplerSampler2D, \1, \2, \3).rgb"),
    (re.compile(r"mtlx_tex_lookup_grad_rgba\(([^,)]+),\s*([^,)]+),\s*([^)]+)\)"), r"textureSampleGrad($texSamplerSampler2D, \1, \2, \3)"),
    # textureSample restores (from texture placeholders — implicit derivatives)
    (re.compile(r"mtlx_tex_lookup_rgb\(([^,)]+),\s*[^)]+\)"),  r"textureSample($texSamplerSampler2D, \1).rgb"),
    (re.compile(r"mtlx_tex_lookup_rgba\(([^)]+)\)"),            r"textureSample($texSamplerSampler2D, \1)"),
    (re.compile(r"mtlx_tex_lookup_rg\(([^)]+)\)"),              r"textureSample($texSamplerSampler2D, \1).rg"),
    (re.compile(r"mtlx_tex_lookup_b\(([^)]+)\)"),               r"textureSample($texSamplerSampler2D, \1).b"),
    (re.compile(r"mtlx_tex_lookup_r\(([^)]+)\)"),               r"textureSample($texSamplerSampler2D, \1).r"),
]

# Sampler-stub patterns emitted by naga for the `$texSamplerSignature` placeholder.
# GLSL order (`i32 mtlx_sampler_stub`) appears with cleanup; WGSL order
# (`mtlx_sampler_stub: i32`) appears without it. Both need restoration.
_SAMPLER_STUB_GLSL_ORDER = re.compile(r"\bi32 mtlx_sampler_stub(?:_\d+)?\b")
_SAMPLER_STUB_WGSL_ORDER = re.compile(r"mtlx_sampler_stub(?:_\d+)?:\s*i32\b")
_SAMPLER_STUB_VAR_DECL   = re.compile(r"^\s*var mtlx_sampler_stub(?:_\d+)?:\s*i32;\s*\n", re.M)
_SAMPLER_STUB_COPY_IN    = re.compile(
    r"^\s*mtlx_sampler_stub(?:_\d+)?\s*=\s*mtlx_sampler_stub(?:_\d+)?;\s*\n", re.M)


def _restoreTexLookups(text):
    '''Replace naga placeholder calls with WGSL textureSample($texSamplerSampler2D, …).'''
    for rx, repl in _TEX_LOOKUP_RULES:
        text = rx.sub(repl, text)
    return text


def _restoreSamplerSignatures(text):
    '''Restore $texSamplerSignature in function signatures and remove naga's param-copy shadows.

    Naga replaces the `int mtlx_sampler_stub` placeholder with either GLSL-order (`i32 name`)
    or WGSL-order (`name: i32`) depending on the transpile path. It also emits a `var` shadow
    and copy-in assignment that tree-sitter cleanup normally removes.'''
    # Already-restored token followed by `: i32` (from a prior token restore pass).
    text = re.sub(r"\$texSamplerSignature:\s*i32\b", "$texSamplerSignature", text)
    # Replace sampler stubs inside function signatures only (not var declarations).
    text = re.sub(
        r"(fn\s+\w+\s*\()([^)]*)(\))",
        lambda m: m.group(1)
                  + _SAMPLER_STUB_WGSL_ORDER.sub("$texSamplerSignature",
                    _SAMPLER_STUB_GLSL_ORDER.sub("$texSamplerSignature", m.group(2)))
                  + m.group(3),
        text)
    # Strip naga's param-copy shadows for the sampler stub.
    text = _SAMPLER_STUB_VAR_DECL.sub("", text)
    text = _SAMPLER_STUB_COPY_IN.sub("", text)
    return text


def applyWgslLibPostRestore(text, libroot=None):
    '''WGSL-specific fixes applied after $-token restoration on generated lib/node output.

    Runs four phases in order:
      1. Restore mtlx_* placeholders → $-tokens  (TOKEN_RESTORE_RULES)
      2. Rewrite texture lookups → textureSample() calls
      3. Restore $texSamplerSignature in fn params and clean up naga shadows
      4. Fix i32 uniform arithmetic and split env texture/sampler args
    '''
    # Phase 1: bulk $-token restoration.
    for rx, token in TOKEN_RESTORE_RULES:
        text = rx.sub(token, text)
    # Phase 2: texture-lookup helpers → textureSample().
    text = _restoreTexLookups(text)
    # Phase 3: GLSL→WGSL derivative rename.
    text = re.sub(r"\bdFdx\b", "dpdx", text)
    text = re.sub(r"\bdFdy\b", "dpdy", text)
    # Phase 4: sampler signature restoration.
    text = _restoreSamplerSignatures(text)
    # Phase 5: arithmetic and env-latlong fixups.
    text = patchIntUniformTokenArithmetic(text)
    text = patchWgslEnvLatlongCalls(text)
    return text


def _repoRoot(libroot):
    '''Parent of libroot (the MaterialX repo root when libroot is `libraries/`).'''
    return Path(libroot).resolve().parent


def _readSourceText(path):
    '''Read a repo source file as UTF-8 text.'''
    return path.read_text(encoding="utf-8")


def loadGlslSyntaxSnippets(repoRoot):
    '''Extract struct and #define snippets from MaterialXGenGlsl/GlslSyntax.cpp.

    Parses the AggregateTypeSyntax definition strings (BSDF, VDF, surfaceshader, etc.) and the
    EDF/material aliases exactly as the GLSL generator emits them. Node transpile uses the full set;
    wgslClosurePreamble uses BSDF/VDF only (ClosureData/FresnelData come from genglsl/lib).'''
    path = repoRoot / "source" / "MaterialXGenGlsl" / "GlslSyntax.cpp"
    text = _readSourceText(path)
    snippets = {}
    for name in _GLSL_SYNTAX_STRUCT_NAMES:
        m = re.search(rf'"struct {name} \{{[^"]+\}};"', text)
        if m:
            snippets[name] = m.group(0).strip('"')
    for key, pattern in (("EDF", r'"#define EDF vec3"'),
                         ("material", r'"#define material surfaceshader"')):
        m = re.search(pattern, text)
        if m:
            snippets[key] = m.group(0).strip('"')
    return snippets


def _emitWgslStructsFromGlsl(text, only=None, skip=None):
    '''Convert selected GLSL struct definitions in `text` to WGSL struct blocks.

    Shared by wgslClosurePreamble and transpileGlslStructs. Strips GLSL comments, maps scalar/
    vector types via GLSL_TO_WGSL_TYPE, and rewrites array fields (`name[N]` -> `array<T, N>`).
    When `only` is set, emit just those struct names (used to pull ClosureData/FresnelData from lib
    files without re-emitting every struct in the source). When `skip` is set, omit those names
    (used to drop closure structs provided centrally by wgslClosurePreamble).'''
    out = []
    for m in re.finditer(r"\bstruct\s+(\w+)\s*\{([^}]*)\}\s*;?", text):
        name = m.group(1)
        if only is not None and name not in only:
            continue
        if skip is not None and name in skip:
            continue
        bodySrc = re.sub(r"/\*.*?\*/", "", m.group(2), flags=re.S)
        bodySrc = re.sub(r"//[^\n]*", "", bodySrc)
        fields = []
        for part in bodySrc.split(";"):
            part = part.strip()
            if not part:
                continue
            tokens = part.split()
            if len(tokens) < 2:
                continue
            ftype, fname = tokens[0], tokens[1]
            wtype = glslTypeToWgsl(ftype)
            arr = re.match(r"(\w+)\[(\d+)\]$", fname)
            if arr:
                fname, wtype = arr.group(1), f"array<{wtype}, {arr.group(2)}>"
            fields.append(f"    {fname}: {wtype},")
        if fields:
            body = "\n".join(fields).rstrip(",")
            out.append(f"struct {name} {{\n{body}\n}}")
    return out


def _buildWgslClosurePreamble(libroot):
    '''Build the WGSL struct preamble prepended to mx_closure_type.wgsl.

    Replaces the former LIB_STRUCT_PREAMBLE hand-written block. Sources:
      - ClosureData  from libraries/pbrlib/genglsl/lib/mx_closure_type.glsl
      - BSDF, VDF    from GlslSyntax.cpp (same layout as GLSL generator)
      - EDF, material aliases (vec3f / surfaceshader)
      - FresnelData  from libraries/pbrlib/genglsl/lib/mx_microfacet_specular.glsl
    surfaceshader is omitted here (WgslShaderGenerator::emitTypeDefinitions owns it).'''
    libroot = Path(libroot).resolve()
    repo = _repoRoot(libroot)
    parts = []
    closureSrc = _readSourceText(libroot / "pbrlib" / "genglsl" / "lib" / "mx_closure_type.glsl")
    specSrc = _readSourceText(libroot / "pbrlib" / "genglsl" / "lib" / "mx_microfacet_specular.glsl")
    parts.extend(_emitWgslStructsFromGlsl(closureSrc, only={"ClosureData"}))
    snippets = loadGlslSyntaxSnippets(repo)
    for name in ("BSDF", "VDF"):
        parts.extend(_emitWgslStructsFromGlsl(snippets[name]))
    parts.append("alias EDF = vec3f;")
    parts.append("alias material = surfaceshader;")
    parts.extend(_emitWgslStructsFromGlsl(specSrc, only={"FresnelData"}))
    return "\n\n".join(parts) + "\n"


